#!/usr/bin/env python3
"""Write an explicitly incomplete audit from the narrow-verification round-2 trace file.

    uv run --no-sync python scripts/m6_level2_narrow_verify2_audit.py

The full report script (``m6_level2_narrow_verify2_report.py``) requires 54
traces and refuses to write anything from an incomplete run. This audit exists
only for that case: it reads the same trace file, states the missing
configurations, and derives every number from the traces. It never claims the
run is complete and does not replace the full report.

No API calls, no key reads, no source-fingerprint changes.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent

TRACE_PATH = REPOSITORY_ROOT / "docs" / "benchmarks" / "m6-level2-narrow-verify2-traces.json"
REPORT_PATH = REPOSITORY_ROOT / "docs" / "benchmarks" / "m6-level2-narrow-verify2-incomplete.md"

NARROW_TASK_IDS: tuple[str, ...] = (
    "manifest.permission.count-obfuscated",
    "overloads.method-identity.descriptor-distinguishes",
    "strings.api-key.demo",
    "resources.app-name.demo",
    "partial.no-apktool-there-is-no-manifest",
    "multidex.dex-file-count",
)
SYSTEMS = ("A", "B", "DexAtlas")
ROUNDS = 3
FULL_EXPECTED = len(NARROW_TASK_IDS) * ROUNDS * len(SYSTEMS)
AGENT = "DexAtlas"
ORIGINAL_LIMIT = 410_000
AMENDED_LIMIT = 410_000
CODE_STATE = "claude/m6-level2-verify 9b25835"
DETERMINISTIC = frozenset(NARROW_TASK_IDS) - {"overloads.method-identity.descriptor-distinguishes"}


def tokens(trace: dict[str, Any]) -> int:
    result = trace["result"]
    return int(result["prompt_tokens"]) + int(result["completion_tokens"])


def outcome(trace: dict[str, Any]) -> str:
    """Same vocabulary as the full report, read from trace fields only."""
    result = trace["result"]
    if result.get("outcome") == "budget-exhausted":
        return "budget-exhausted"
    if trace.get("passed"):
        return "correct"
    if result.get("failed"):
        if "budget" in result.get("error", "") or "ran out" in result.get("error", ""):
            return "budget-exhausted"
        if not result.get("error"):
            return "no-answer"
        return "errored"
    if trace.get("answer_is_empty"):
        return "empty"
    return "wrong"


def load() -> list[dict[str, Any]]:
    if not TRACE_PATH.exists():
        raise SystemExit(f"trace file missing: {TRACE_PATH}")
    document = json.loads(TRACE_PATH.read_text(encoding="utf-8"))
    return list(document["traces"])


def render(traces: list[dict[str, Any]]) -> str:
    seen = {(t["_round"], t["task_id"], t["system"]) for t in traces}
    missing = [
        (r, task, system)
        for r in range(1, ROUNDS + 1)
        for task in NARROW_TASK_IDS
        for system in SYSTEMS
        if (r, task, system) not in seen
    ]
    total = sum(tokens(t) for t in traces)
    counts: Counter[str] = Counter(outcome(t) for t in traces if t["system"] == AGENT)

    agent_rows: list[str] = []
    converted: list[str] = []
    deterministic_converted: list[str] = []
    for task in NARROW_TASK_IDS:
        task_traces = sorted(
            (t for t in traces if t["system"] == AGENT and t["task_id"] == task),
            key=lambda t: t["_round"],
        )
        cells = [f"r{t['_round']}={outcome(t)}" for t in task_traces]
        available = sum(1 for t in task_traces if outcome(t) == "correct")
        rounds_seen = len(task_traces)
        if available >= 2:
            converted.append(task)
            if task in DETERMINISTIC:
                deterministic_converted.append(task)
        agent_rows.append(
            f"| `{task}` | {', '.join(cells) if cells else 'none'} | {available}/{rounds_seen} |"
        )

    gate = len(converted) >= 4 and len(deterministic_converted) >= 3
    lines = [
        "# M6 level-2 narrow verification round 2 - INCOMPLETE trace audit",
        "",
        f"**Status: INCOMPLETE RUN.** Code state: `{CODE_STATE}`. "
        f"This file is generated by `scripts/m6_level2_narrow_verify2_audit.py` "
        f"from `{TRACE_PATH.name}`. It does not replace "
        "`m6-level2-narrow-verify.md`; the full report script refuses to write "
        "a report for fewer than 54 traces and that refusal is kept intact.",
        "",
        "## Trace completeness",
        "",
        f"- Expected: {FULL_EXPECTED} traces (3 configurations x "
        f"{len(NARROW_TASK_IDS)} tasks x {ROUNDS} rounds).",
        f"- Captured: {len(traces)} traces.",
        f"- Missing: {len(missing)} traces.",
    ]
    for r, task, system in missing:
        lines.append(f"  - round {r}, task `{task}`, system `{system}`")
    lines += [
        "",
        "## Budget",
        "",
        f"- Authorisation for this round: {ORIGINAL_LIMIT:,} tokens, checked "
        "at every batch boundary (one task = one A/B/DexAtlas invocation = 3 "
        "traces), so the final batch can finish slightly past the line.",
        f"- Actual total from the captured traces: **{total:,} tokens** "
        + (
            f"({total - ORIGINAL_LIMIT:,} over the limit). "
            if total > ORIGINAL_LIMIT
            else "(inside the limit). "
        )
        + "The driver stopped at the first batch boundary past the fuse; "
        "the traces listed above are everything that was run. No figures are "
        "extrapolated to the missing traces.",
        "",
        "## DexAtlas outcomes (from captured traces only)",
        "",
        "| task | captured rounds | correct / rounds seen |",
        "|---|---|---|",
        *agent_rows,
        "",
        "- Outcome counts across captured DexAtlas traces: "
        + ", ".join(
            f"{key}={counts.get(key, 0)}"
            for key in ("correct", "wrong", "empty", "no-answer", "budget-exhausted", "errored")
        ),
        f"- Tasks converted (at least 2 correct rounds): "
        f"**{len(converted)}/6**"
        + (f" ({', '.join('`' + t + '`' for t in converted)})" if converted else ""),
        f"- Deterministic-fix subset converted: "
        f"**{len(deterministic_converted)}/5**"
        + (
            f" ({', '.join('`' + t + '`' for t in deterministic_converted)})"
            if deterministic_converted
            else ""
        ),
        f"- Narrow gate (>=4/6 converted and >=3/5 deterministic subset): "
        f"**{'MET on the captured rounds' if gate else 'NOT MET'}**. "
        "This is not a 54-trace verdict.",
        "",
        "## Reproduction",
        "",
        "```bash",
        "uv run --no-sync python scripts/m6_level2_narrow_verify2_audit.py",
        "uv run --no-sync python scripts/m6_level2_narrow_verify2_report.py",
        "# The second command must refuse unless the run reached 54 traces.",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    traces = load()
    REPORT_PATH.write_text(render(traces), encoding="utf-8")
    print(
        f"wrote {REPORT_PATH.relative_to(REPOSITORY_ROOT)} "
        f"({len(traces)} traces, {sum(tokens(t) for t in traces):,} tokens, "
        "incomplete run)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
